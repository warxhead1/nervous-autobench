# Regex captures a fenced block: ``` optionally followed by a language tag,
# then a newline, then the body, then a closing ``` on its own line (or
# end-of-string).
_FENCED_RE = re.compile(
    r"```(?:[a-zA-Z0-9_+\-]*)\s*\n?(.*?)(?:\n```|```|\Z)",
    re.DOTALL,
)

# Strips <think>...</think> blocks that MiniMax-M2.7 sometimes emits even in
# the OpenAI-compatible response. The Anthropic-compatible endpoint serialises
# thinking into a separate content block of type "thinking", which _parse_response
# discards before reaching _extract_code — but this defensive strip catches the
# OpenAI path and any stray inline traces.
_THINK_BLOCK_RE = re.compile(
    r"<think>.*?(?:</think>|\Z)\s*",
    re.DOTALL | re.IGNORECASE,
)

# Leading prose patterns we strip when no fenced block is present. These are
# heuristics — the worker's system prompt asks for "no preamble", but real
# LLMs often inject one anyway.
_PROSE_PREFIX_RE = re.compile(
    r"^(?:here['']?s?\s+(?:the\s+)?(?:solution|code|answer)[:\s\.]*|"
    r"sure[!,\.]?\s+|"
    r"certainly[!,\.]?\s+|"
    r"i['']?ll\s+(?:provide|write|solve)[^\n]*\n)",
    re.IGNORECASE,
)


def _extract_code(raw_text: str) -> str:
    """Strip <think> blocks, markdown fences, and leading prose from an LLM response.

    Strategy:
        1. Strip any ``<think>...</think>`` (or unclosed ``<think>...EOF``)
           blocks first. The Anthropic endpoint normally prevents these from
           reaching us, but the OpenAI endpoint inlines them, and either
           endpoint can occasionally leak.
        2. If a fenced block is present (```python ... ``` or just ``` ... ```),
           return the body of the FIRST such block.
        3. Otherwise, strip a leading prose preamble like "Here's the
           solution:\n" and return the remainder.
        4. Always strip surrounding whitespace.
    """
    if not raw_text:
        return ""

    # Step 1: strip thinking traces.
    raw_text = _THINK_BLOCK_RE.sub("", raw_text)

    # Step 2: try fenced extraction.
    m = _FENCED_RE.search(raw_text)
    if m and m.group(1).strip():
        return m.group(1).strip()

    # Step 3: no fences — strip leading prose.
    stripped = _PROSE_PREFIX_RE.sub("", raw_text.lstrip(), count=1)
    return stripped.strip()


def _parse_response(
    response_json: dict[str, Any], endpoint_mode: str
) -> tuple[str, int, int]:
    """Parse a MiniMax response into ``(raw_text, input_tokens, output_tokens)``.

    Branches on ``endpoint_mode``:
      - ``"openai"``: ``choices[0].message.content`` is a string; usage has
        ``prompt_tokens`` / ``completion_tokens``.
      - ``"anthropic"``: ``content`` is a list of blocks like
        ``[{"type": "thinking", "thinking": "..."}, {"type": "text", "text": "..."}]``.
        We concatenate ONLY the ``"text"`` blocks — thinking blocks are
        deliberately discarded at parse time, not at extraction time, so the
        downstream ``_extract_code`` heuristics never see them. Usage carries
        ``input_tokens`` / ``output_tokens`` (no ``prompt_`` / ``completion_``
        prefix in Anthropic's schema).

    Raises:
        KeyError / IndexError / TypeError on malformed payloads — the caller
        wraps these into a WorkerResult.error string.
    """
    if endpoint_mode == "anthropic":
        blocks = response_json["content"]  # KeyError if missing
        text_parts: list[str] = []
        for block in blocks:
            if isinstance(block, dict) and block.get("type") == "text":
                text_parts.append(str(block.get("text", "")))
        raw_text = "".join(text_parts)
        usage = response_json.get("usage", {}) or {}
        input_tokens = int(usage.get("input_tokens", 0) or 0)
        output_tokens = int(usage.get("output_tokens", 0) or 0)
        return raw_text, input_tokens, output_tokens

    # openai
    raw_text = response_json["choices"][0]["message"]["content"]
    usage = response_json.get("usage", {}) or {}
    input_tokens = int(usage.get("prompt_tokens", 0) or 0)
    output_tokens = int(usage.get("completion_tokens", 0) or 0)
    return raw_text, input_tokens, output_tokens


def _calc_backoff_ms(attempt: int, error: Exception) -> int:
    """Exponential backoff (1s, 2s, 4s, ...) with ~20% jitter.

    Honours ``Retry-After`` header on ``httpx.HTTPStatusError`` when present.
    """
    base_ms = 1000 * (1 << (attempt - 1))
    jitter_ms = int(base_ms * 0.2 * random.random())
    total_ms = base_ms + jitter_ms

    resp = getattr(error, "response", None)
    if resp is not None and hasattr(resp, "headers"):
        retry_after = resp.headers.get("Retry-After")
        if retry_after:
            try:
                total_ms = int(float(retry_after)) * 1000
            except (ValueError, TypeError):
                pass

    return total_ms


